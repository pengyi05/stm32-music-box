/*
 * ============================================================================
 *  key.c —— 【早期版本，当前工程未引用】
 * ============================================================================
 *
 *  本文件是项目早期的按键扫描模块，Keil 工程 atm89.uvproj 未引用本文件。
 *  完整实现见 main.c 中的 check_play_pause / check_next / check_prev。
 *
 *  【与最终版的差异】
 *      本文件：三个按键分别定义为 P3^0、P3^1、P3^2，
 *              消抖方式为 "检测 -> 延时10ms -> 等待释放"
 *      main.c：三个按键定义为 P3^1、P3^2、P3^3，
 *              消抖方式为 "检测 -> 延时消抖 -> 二次确认 -> 等待释放"
 *
 *  【为什么最终版修改了引脚分配】
 *    P3^0 在早期版本中被用作按键，但该引脚同时是 8051 的
 *    INT0（外部中断0）输入，且部分开发板将 P3.0 拉高为板载资源。
 *    最终版将按键统一移至 P3^1~P3^3，避开 P3.0 以减少潜在冲突。
 *
 *  ============================================================================
 */

#include <REGX52.H>
#include "delay.h"
#include "music.h"

/* ===========================================================================
 *  按键引脚定义（早期版本）
 * =========================================================================*/

sbit KEY1 = P3^0;     /* 未在早期版本中使用 */
sbit KEY2 = P3^1;     /* 上一曲 */
sbit KEY3 = P3^2;     /* 下一曲 */

/* ===========================================================================
 *  Key_Scan —— 按键扫描
 * ===========================================================================
 *
 *  在主循环中被反复调用，检测到按键后修改 music.c 中的 song_id 变量。
 *
 *  【消抖方式】
 *    采用 "检测到按下 -> DelayMs(10) -> while 等待释放" 的方式。
 *    原理：机械按键在按下瞬间存在几十毫秒的机械抖动，若不处理会被
 *    识别为多次连续点击。延时 10ms 后若按键仍为按下状态，则确认为
 *    真实按下；随后通过 while 循环等待释放，防止一次按下被当作多次。
 *
 *  【与最终版的差异】
 *    最终版 main.c 中增加了一次"二次确认"判断（延时后再判断一次电平），
 *    比单纯等待释放更可靠 —— 因为若抖动持续时间超过 10ms，
 *    仅靠等待释放仍可能误判。
 */
void Key_Scan(void)
{
    /* 上一曲：仅在 song_id 大于 0 时递减，避免下溢 */
    if(KEY2 == 0) {
        DelayMs(10);            /* 延时消抖 */
        while(KEY2 == 0);       /* 等待按键释放 */
        if(song_id > 0)
            song_id--;
    }

    /* 下一曲：递增曲目号 */
    if(KEY3 == 0) {
        DelayMs(10);
        while(KEY3 == 0);
        song_id++;
    }
}