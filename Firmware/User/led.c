#include <REGX52.H>

/* 当前流水灯位置（0~7） */
unsigned char pos = 0;

/* ===========================================================================
 *  LED_Init —— LED 端口初始化
 * ===========================================================================
 *
 *  设置 P2 口全部输出为高电平。
 *  对于共阳极接法的 LED，输出高电平即为熄灭（不点亮）。
 */
void LED_Init()
{
    P2 = 0xFF;
}

/* ===========================================================================
 *  LED_Flow —— 流水灯
 * ===========================================================================
 *
 *  每次调用点亮一位 LED，并将位置指针循环移动。
 *  被主循环反复调用即可形成流水灯效果。
 *
 *  【位运算说明】
 *    P2 = ~(1 << pos) 的作用：
 *      1 << pos 生成只有第 pos 位为 1 的掩码；
 *      取反后变为"只有第 pos 位为 0，其余位为 1"；
 *      赋给 P2 即实现"仅点亮第 pos 位的 LED"（共阳极接法下输出低电平点亮）。
 *
 *    pos = (pos+1) % 8 实现指针在 0~7 之间循环，不会越界。
 */
void LED_Flow()
{
    P2 = ~(1 << pos);       /* 点亮当前位 */
    pos = (pos + 1) % 8;    /* 移动到下一位，循环 */
}