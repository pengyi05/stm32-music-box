/*
 * ============================================================================
 *  delay.c —— 毫秒级延时函数（最终版本）
 * ============================================================================
 *
 *  本文件是工程中唯一被最终版本 main.c 之外的模块引用的驱动文件。
 *
 *  【关于精度的说明】
 *  本延时采用"空循环"方式，实际时间取决于：
 *    - 晶振频率（本项目 11.0592MHz）
 *    - 编译器优化等级（Keil C51 默认优化会改变循环次数的执行时间）
 *    - 8051 的机器周期数（一个机器周期 = 12 个振荡周期 ≈ 1.085us）
 *
 *  因此本函数的延时值不精确，仅适用于对时间精度要求不高的场景：
 *    - LED 点阵刷新保持
 *    - 按键消抖
 *    - LED 跑马灯等视觉效果
 *
 *  【重要】项目中对时间精度有要求的部分（音符时值）并未使用本函数，
 *  而是采用定时器1 中断累减计时的方式实现，见 main.c 的 t1_isr()。
 *  这样计时精度不受主循环执行时间与编译器优化影响。
 *
 * ============================================================================
 */

/*
 * DelayMs —— 阻塞式毫秒延时
 *
 * 参数 ms —— 期望延时的毫秒数
 *
 * 实现：双层空循环。外层计毫秒，内层凑够一个毫秒所需的循环次数。
 * 内层常量 123 是在 11.0592MHz 晶振下的经验值，
 * 若更换晶振频率或编译器版本，需要重新标定该常量。
 */
void DelayMs(unsigned int ms)
{
    unsigned int i, j;

    for(i = 0; i < ms; i++)          /* 外层：毫秒计数 */
        for(j = 0; j < 123; j++);    /* 内层：凑满 1ms 所需的空循环 */
}